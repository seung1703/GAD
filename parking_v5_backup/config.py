def _load_calib():
    """calib.json 을 읽어 기본값 위에 덮어쓴다. 실패해도 주차는 돌아가야
    하므로 예외를 삼키고 기본값으로 진행한다 (대신 경고를 남긴다)."""
    vals = dict(_HOME_DEFAULTS)
    try:
        with open(CALIB_PATH, encoding="utf-8") as f:
            data = _json.load(f)
    except FileNotFoundError:
        return vals
    except (ValueError, OSError) as e:
        print(f"[config] calib.json 읽기 실패 → 기본값 사용: {e}")
        return vals
    for k in vals:
        if k in data:
            vals[k] = data[k]
    return vals


